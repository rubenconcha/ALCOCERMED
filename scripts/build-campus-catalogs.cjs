'use strict';
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { runInNewContext } = require('node:vm');
const mapContext = { window: {} };
runInNewContext(readFileSync(join(__dirname, '..', 'mindmap-premium-catalog.js'), 'utf8'), mapContext);
const cardMetadata = ({ id, titulo, materia, tema, orden, acceso_gratis }) => ({ id, titulo, materia, tema, orden, acceso_gratis });
const sheets = mapContext.window.MINDMAP_PREMIUM_CATALOG.filter(map => map.curated || map.section === 'intocables');
const { catalog } = require('../api/_flashcards/library.json');
const data = {
    flashcards: catalog.map(({ materia, tema, count }) => ({ materia, tema, count })),
    past: require('../content/past-exams/catalog.json'),
    simulations: require('../content/simulacros-catalog.json'),
    evaluations: { exams: require('../content/topic-evaluations/catalog.json').exams.concat(require('../api/_evaluations/suficiencia.cjs').metadata()) },
    intocables: require('../content/intocables_catalogo_2026.json').map(item => ({ ...cardMetadata(item), kind: 'cards' }))
        .concat(sheets.map((map, index) => ({
            ...cardMetadata(map), kind: 'sheets', orden: index + 1,
            tema: map.id.startsWith('morfo_18_sangre__') ? 'Sangre' : map.tema,
        }))),
};
writeFileSync(join(__dirname, '..', 'campus-catalogs.js'),
    '// Generated by scripts/build-campus-catalogs.cjs. Titles, counts and exam metadata only.\nwindow.CampusCatalogs = ' +
    JSON.stringify(data) + ';\n');
